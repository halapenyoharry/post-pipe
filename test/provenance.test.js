// provenance.js: the why and the PROV pair an edge's hover label shows.
const test = require('node:test');
const assert = require('node:assert');
const { evidencePhrase, provenanceLines, tagEdgeLabel } = require('../src/lib/provenance');
const { relationLabel, relativeLabel } = require('../src/lib/tagNetwork');

const discovered = {
  why: 'recurs in 7 of 102 items, which stay alike without it (0.05, 3.0× the 0.016 that items from the same sources share)',
  wasDerivedFrom: [{ type: 'text', phrase: 'cancer', count: 1, inTitle: false }],
  wasGeneratedBy: { activity: 'discover', parameters: { minDf: 2, sourceCoherenceRatio: 1.6, df: 7, sourceRatio: 2.964 } },
};

test('a card-to-tag edge says its role, its why, then where it was derived from and what generated it', () => {
  const label = tagEdgeLabel({ source: 'a', target: 'tag:cancer', layer: 'tag', role: 'tagged', attrs: { concept: 'c_cancer', weight: 0.4, origin: 'discovered', ...discovered } });
  const lines = label.split('\n');
  assert.strictEqual(lines[0], 'tagged');
  const text = lines.join(' ');
  assert.ok(text.includes(discovered.why), 'the why, whole');
  assert.ok(text.includes('derived from: "cancer" in the text, 1×'));
  assert.ok(text.includes('generated by: discover, with minDf 2, sourceCoherenceRatio 1.6, df 7, sourceRatio 2.964'));
  assert.ok(lines.includes('sourceRatio 2.964') || lines.some((l) => l.endsWith('sourceRatio 2.964')), 'a parameter and its value stay on one line');
  for (const l of lines) assert.ok(l.length <= 48, `line within 48: ${l}`);
});

test('a tag a person wrote: no why, derived from the tag as its system wrote it, generated by ingest', () => {
  const label = tagEdgeLabel({ layer: 'tag', role: 'tagged', attrs: {
    concept: 'c_ai', origin: 'explicit',
    wasDerivedFrom: [{ type: 'category', scheme: 'Journal', label: 'AI' }, { type: 'category', scheme: 'Posts', label: 'ai' }],
    wasGeneratedBy: { activity: 'ingest', parameters: {} },
  } });
  assert.deepStrictEqual(label.split('\n'), ['tagged', 'derived from: the tag "AI" written in Journal;', 'the tag "ai" written in Posts', 'generated by: ingest']);
});

test('an edge with no why and no provenance says only its role, as before', () => {
  assert.strictEqual(tagEdgeLabel({ layer: 'tag', role: 'tagged' }), 'tagged');
  assert.strictEqual(tagEdgeLabel({ layer: 'tag', role: 'tagged', attrs: { concept: 'c_x', weight: 1, origin: 'explicit' } }), 'tagged');
  assert.strictEqual(tagEdgeLabel({ layer: 'tag', label: 'flashback', role: 'tagged' }), 'flashback');
});

test('each kind of evidence rosetta-tagz writes reads as a plain phrase', () => {
  assert.strictEqual(evidencePhrase({ type: 'cooccurrence', items: 2 }), '2 items carrying both');
  assert.strictEqual(evidencePhrase({ type: 'stem', key: 'brain' }), 'the shared words "brain"');
  assert.strictEqual(evidencePhrase({ type: 'text', cosine: 0.31 }), 'texts alike, cosine 0.31');
  assert.strictEqual(evidencePhrase({ type: 'signal', name: 'stem', score: 0.92 }), 'the stem signal 0.92');
  assert.strictEqual(evidencePhrase({ type: 'seed' }), 'a seed list');
  assert.strictEqual(evidencePhrase({ type: 'override', note: 'Harold said so' }), 'an override (Harold said so)');
  assert.strictEqual(evidencePhrase({ type: 'text', phrase: 'Jupiter', count: 2, inTitle: true }), '"Jupiter" in the text, 2×, in the title');
  assert.strictEqual(evidencePhrase({ type: 'novel', x: 1, y: [2] }), 'novel x 1 y [2]', 'an unknown kind says what it holds');
});

test('a PROV field absent, null or empty writes no line', () => {
  assert.deepStrictEqual(provenanceLines({}), []);
  assert.deepStrictEqual(provenanceLines(null), []);
  assert.deepStrictEqual(provenanceLines({ wasDerivedFrom: [], wasGeneratedBy: null }), []);
  assert.deepStrictEqual(provenanceLines({ wasGeneratedBy: { activity: 'relate', parameters: { source: 'seed', minNpmi: null } } }), ['generated by: relate, with source seed']);
});

test('a relation line adds the PROV pair to its type, weight and why', () => {
  const r = {
    source: 'tag:active', target: 'tag:carrying', layer: 'related', role: 'related',
    attrs: { weight: 0.32, why: 'share 2 items', wasDerivedFrom: [{ type: 'cooccurrence', items: 2 }], wasGeneratedBy: { activity: 'relate', parameters: { minNpmi: 0.25, minCooc: 2 } } },
  };
  assert.deepStrictEqual(relationLabel([r]).split('\n'), [
    'related · weight 0.32', 'share 2 items', 'derived from: 2 items carrying both', 'generated by: relate, with minNpmi 0.25,', 'minCooc 2',
  ]);
  const bubble = { id: 'tag:music', members: [{ id: 'tag:jazz', relations: [r] }] };
  assert.deepStrictEqual(relativeLabel(bubble).split('\n'), [
    'jazz · related · weight 0.32', 'share 2 items', 'derived from: 2 items carrying both', 'generated by: relate, with minNpmi 0.25,', 'minCooc 2',
  ]);
});
